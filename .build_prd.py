def p(text):
    return add_runs(doc.add_paragraph(), text)


def bullets(items, level=1):
    for item in items:
        if isinstance(item, (list, tuple)):
            bullets(item, level=2)
            continue
        add_runs(doc.add_paragraph(style='List Bullet' if level == 1 else 'List Bullet 2'), item)


def _shade(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), fill)
    tc_pr.append(shd)


def _tbl_props(table):
    tbl_pr = table._tbl.tblPr
    look = tbl_pr.find(qn('w:tblLook'))
    # tblLayout=fixed 已由 table.autofit = False 写入，这里只补单元格边距（须位于 tblLook 之前）
    mar = OxmlElement('w:tblCellMar')
    for side, val in (('top', 50), ('left', 100), ('bottom', 50), ('right', 100)):
        el = OxmlElement(f'w:{side}')
        el.set(qn('w:w'), str(val))
        el.set(qn('w:type'), 'dxa')
        mar.append(el)
    if look is not None:
        look.addprevious(mar)
    else:
        tbl_pr.append(mar)
    # 显式表格边框（不依赖 Table Grid 样式，兼容 WPS / Pages / 预览）；tblBorders 须位于 shd/tblLayout/tblCellMar/tblLook 之前
    borders = OxmlElement('w:tblBorders')
    for side in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        el = OxmlElement(f'w:{side}')
        el.set(qn('w:val'), 'single')
        el.set(qn('w:sz'), '4')
        el.set(qn('w:space'), '0')
        el.set(qn('w:color'), 'C9D1DC')
        borders.append(el)
    anchor = next((c for c in tbl_pr if c.tag in {qn('w:shd'), qn('w:tblLayout'), qn('w:tblCellMar'), qn('w:tblLook')}), None)
    if anchor is not None:
        anchor.addprevious(borders)
    else:
        tbl_pr.append(borders)


def _fill_cell(cell, text, bold=False, size=9.5):
    lines = str(text).split('\n')
    cell.paragraphs[0].text = ''
    for idx, line in enumerate(lines):
        para = cell.paragraphs[0] if idx == 0 else cell.add_paragraph()
        para.paragraph_format.space_after = Pt(1)
        para.paragraph_format.line_spacing = 1.2
        add_runs(para, f'**{line}**' if bold and line else line, size=size)


def table(headers, rows, widths):
    assert abs(sum(widths) - CONTENT_CM) < 0.01, (headers, sum(widths))
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    _tbl_props(t)
    for i, w in enumerate(widths):
        t.columns[i].width = Cm(w)
    head = t.rows[0]
    tr_pr = head._tr.get_or_add_trPr()
    rep = OxmlElement('w:tblHeader')
    rep.set(qn('w:val'), 'true')
    tr_pr.append(rep)
    for i, text in enumerate(headers):
        cell = head.cells[i]
        cell.width = Cm(widths[i])
        _fill_cell(cell, text, bold=True)
        _shade(cell, 'EEF2F7')
    for row in rows:
        cells = t.add_row().cells
        for i, text in enumerate(row):
            cells[i].width = Cm(widths[i])
            _fill_cell(cells[i], text)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def note(text, title='说明'):
    t = doc.add_table(rows=1, cols=1)
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    _tbl_props(t)
    t.columns[0].width = Cm(CONTENT_CM)
    cell = t.rows[0].cells[0]
    cell.width = Cm(CONTENT_CM)
    _fill_cell(cell, f'**{title}：**{text}', size=9.5)
    _shade(cell, 'FFF8E6')
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def page_break():
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def add_field(paragraph, instr, placeholder=''):
    def fld(kind):
        el = OxmlElement('w:fldChar')
        el.set(qn('w:fldCharType'), kind)
        r = paragraph.add_run()
        r._r.append(el)

    fld('begin')
    r = paragraph.add_run()
    it = OxmlElement('w:instrText')
    it.set(qn('xml:space'), 'preserve')
    it.text = instr
    r._r.append(it)
    fld('separate')
    paragraph.add_run(placeholder)
    fld('end')


def enable_update_fields():
    settings = doc.settings.element
    zoom = settings.find(qn('w:zoom'))
    if zoom is not None and zoom.get(qn('w:percent')) is None:
        zoom.set(qn('w:percent'), '100')
    later = {'hdrShapeDefaults', 'footnotePr', 'endnotePr', 'compat', 'docVars', 'rsids', 'mathPr',
             'attachedSchema', 'themeFontLang', 'clrSchemeMapping', 'doNotIncludeSubdocsInStats',
             'doNotAutoCompressPictures', 'forceUpgrade', 'captions', 'readModeInkLockDown', 'smartTagType',
             'schemaLibrary', 'shapeDefaults', 'doNotEmbedSmartTags', 'decimalSymbol', 'listSeparator'}
    el = OxmlElement('w:updateFields')
    el.set(qn('w:val'), 'true')
    for child in settings:
        if child.tag.split('}')[-1] in later:
            child.addprevious(el)
            return
    settings.append(el)


