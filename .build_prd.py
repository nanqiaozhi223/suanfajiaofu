# ---------- 段落工具 ----------
def add_runs(paragraph, text, size=None, color=None):
    """支持 **加粗** 标记。"""
    for i, part in enumerate(re.split(r'\*\*', text)):
        if not part:
            continue
        run = paragraph.add_run(part)
        run.bold = (i % 2 == 1) or None
        if size:
            run.font.size = Pt(size)
        if color:
            run.font.color.rgb = RGBColor(*color)
    return paragraph


